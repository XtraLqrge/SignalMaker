const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ window: {}, console });
for (const name of ['dimensions', 'regulatory-sign-data', 'street-signs', 'signal-model', 'mast-approach', 'signal-renderer']) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', `${name}.js`), 'utf8'), context);
}
const app = context.window.SignalMaker;
assert.equal(app.normalizeSupport().side, 'left');
assert.equal(app.normalizeSupport({ side: 'right' }).side, 'right');
const project = app.restoreProject(null);
project.support.type = 'mast-arm';
const original = app.createHead('First arm');
original.armPosition = 150;
project.heads.push(original);
project.selectedId = original.id;
project.support.angle = 8;
const firstSign = app.createStreetSign('First sign');
project.streetSigns.push(firstSign);
app.addMastArm(project);
assert.equal(project.mastArms.length, 2);
assert.equal(project.activeMastArm, 1);
assert.equal(project.heads.length, 0);
assert.equal(project.support.side, 'left');
project.support.side = 'right';
project.support.length = 600;
const second = app.createHead('Second arm');
second.armPosition = 200;
project.heads.push(second);
project.selectedId = second.id;
const sign = app.createStreetSign('Second sign');
project.streetSigns.push(sign);
project.mastArmSpacing = 900;
app.syncMastArms(project);
const layout = app.scene(project);
assert.equal(layout.assemblies.length, 2);
assert.equal(layout.heads.length, 2);
assert.equal(layout.streetSigns.length, 2);
const centers = layout.assemblies.map(({ layout: local, x }) => x + (local.reversed ? local.mast.width - local.mast.poleX : local.mast.poleX) + (local.supportOffset?.x ?? 0));
assert.equal(centers[1] - centers[0], 900);
const grades = layout.assemblies.map(({ layout: local, y }) => y + local.mast.offsetY + (local.supportOffset?.y ?? 0) + app.dimensions.mast.poleHeight);
assert.equal(grades[0], grades[1]);
const svg = app.renderSVG(project);
assert.ok(svg.includes('First arm'));
assert.ok(svg.includes('Second arm'));
assert.ok(svg.includes('First sign'));
assert.ok(svg.includes('Second sign'));
assert.equal((svg.match(/class="mastArm"/g) ?? []).length, 2);
assert.ok(!svg.includes('NaN'));
assert.ok(app.renderPreview(project).includes('data-mast-arm-index="1"'));
app.selectMastArm(project, 0);
assert.equal(project.heads[0].id, original.id);
assert.equal(project.support.angle, 8);
assert.equal(project.heads[0].armPosition, 150);
assert.equal(app.scene(project).width, layout.width);
app.syncMastArms(project);
const restored = app.restoreProject(JSON.stringify(project));
assert.equal(restored.mastArms.length, 2);
assert.equal(restored.mastArmSpacing, 900);
assert.equal(restored.heads[0].name, 'First arm');
app.selectMastArm(restored, 1);
assert.equal(restored.heads[0].name, 'Second arm');
assert.equal(restored.support.side, 'right');
assert.equal(restored.support.length, 600);
assert.equal(restored.streetSigns[0].name, 'Second sign');
app.removeMastArm(restored);
assert.equal(restored.mastArms.length, 1);
assert.equal(restored.heads[0].name, 'First arm');
assert.equal((app.renderSVG(restored).match(/class="mastArm"/g) ?? []).length, 1);
const singleCopy = { ...project, support: { ...project.support, type: 'none' }, heads: [original], streetSigns: [] };
assert.ok(!app.renderSVG(singleCopy).includes('Second arm'));
console.log('Left default, independent mast arms, pole spacing, grade alignment, preview/export, restoration, removal and individual copy passed');
// The existing drag and spacing-handle inverse mapping must still work within
// the combined scene, including the left-facing selected arm.
for (const index of [0, 1]) {
  app.selectMastArm(project, index);
  const combined = app.scene(project);
  const item = combined.heads.find(item => item.head === project.heads[0]);
  const center = item.x + item.geometry.width / 2;
  const projected = (combined.reversed ? combined.width - center : center) - combined.supportStart;
  assert.ok(Math.abs(app.supportPositionAtX(project.support, projected) - item.head.armPosition) < 0.00001);
  const local = combined.assemblies[index].layout;
  const poleGrade = app.dimensions.mast.poleHeight + combined.mast.offsetY + combined.supportOffset.y;
  const actualGrade = app.dimensions.mast.poleHeight + local.mast.offsetY + (local.supportOffset?.y ?? 0) + combined.assemblies[index].y;
  assert.equal(poleGrade, actualGrade);
}
console.log('Mirrored head dragging and pole-height coordinate mapping passed');
const buttons = Object.fromEntries(['undoButton', 'redoButton'].map(id => [id, { setAttribute() {}, addEventListener() {} }]));
context.navigator = { platform: 'MacIntel' };
context.document = { querySelectorAll: () => [], getElementById: id => buttons[id], addEventListener() {}, activeElement: null };
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js/history.js'), 'utf8'), context);
app.syncMastArms(project);
app.startHistory(project, { onRestore() {}, report() {} });
app.selectMastArm(project, 0);
app.syncMastArms(project);
app.recordHistory();
assert.equal(buttons.undoButton.disabled, true);
app.removeMastArm(project);
app.syncMastArms(project);
app.recordHistory();
assert.equal(project.mastArms.length, 1);
app.undo();
assert.equal(project.mastArms.length, 2);
assert.ok(app.mastArmProjects(project).some(arm => arm.heads.some(head => head.name === 'Second arm')));
app.redo();
assert.equal(project.mastArms.length, 1);
console.log('Arm selection avoids undo steps; removal undo/redo retains both assemblies');
// Reordering carries each entire assembly, retaining names, selected arm,
// head positions and pole spacing. Duplication creates independent entity IDs.
const reordered = app.restoreProject(null);
reordered.support.type = 'mast-arm';
const a = app.createHead('A');
a.armPosition = 160;
reordered.heads.push(a);
reordered.selectedId = a.id;
app.addMastArm(reordered);
const b = app.createHead('B');
b.armPosition = 240;
reordered.heads.push(b);
reordered.selectedId = b.id;
app.syncMastArms(reordered);
const selectedArmId = reordered.mastArmId;
app.reorderMastArms(reordered, 1, 0);
assert.equal(reordered.activeMastArm, 0);
assert.equal(reordered.mastArmId, selectedArmId);
assert.equal(reordered.selectedId, b.id);
assert.equal(reordered.heads[0].armPosition, 240);
assert.equal(reordered.mastArms[1].heads[0].armPosition, 160);
assert.equal(reordered.mastArms[0].mastArmName, 'Mast Arm 2');
assert.equal(reordered.mastArmSpacing, 720);
// Discard the history fixture's document mock, restoring server-side text sizing.
context.document = undefined;
assert.ok(app.renderPreview(reordered).includes('data-select-mast-arm="1"'));
assert.ok(!app.renderPreview(reordered).includes('aria-hidden="true" data-select-mast-arm'));
assert.ok(!app.renderSVG(reordered).includes('data-select-mast-arm'));
app.duplicateMastArm(reordered);
assert.equal(reordered.mastArmName, 'Mast Arm 3');
assert.notEqual(reordered.mastArmId, selectedArmId);
assert.notEqual(reordered.heads[0].id, b.id);
assert.equal(reordered.heads[0].armPosition, 240);
reordered.heads[0].armPosition = 300;
assert.equal(reordered.mastArms[0].heads[0].armPosition, 240);
app.syncMastArms(reordered);
const roundtrip = app.restoreProject(JSON.stringify(reordered));
assert.equal(roundtrip.mastArmId, reordered.mastArmId);
assert.equal(roundtrip.mastArmName, 'Mast Arm 3');
assert.equal(roundtrip.mastArms[0].mastArmName, 'Mast Arm 2');
console.log('Mast-arm reorder selection/position preservation, support targets, independent duplication and name/ID restoration passed');
