const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), assert = require('node:assert/strict');
const context = vm.createContext({ window: {}, console });
for (const name of ['dimensions', 'regulatory-sign-data', 'street-signs', 'signal-model', 'mast-approach', 'signal-renderer', 'templates']) vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', `${name}.js`), 'utf8'), context);
const app = context.window.SignalMaker;
const head = app.createHead('DAD');
app.setHeadLayout(head, 'dad');
assert.equal(head.dad, true);
assert.equal(head.indications.map(i => i.color).join(), 'red,yellow,yellow');
assert.equal(head.indications.map(i => i.symbol).join(), 'ball,left,right');
head.indications[1].size = 8;
const geometry = app.headGeometry(head);
assert.equal(geometry.sections[1].cy, geometry.sections[2].cy);
assert.ok(geometry.sections[0].cy < geometry.sections[1].cy);
assert.ok(geometry.sections[1].cx < geometry.sections[0].cx);
assert.ok(geometry.sections[2].cx > geometry.sections[0].cx);
const support = app.normalizeSupport({ type: 'pedestal', pedestalHeight: 120 });
assert.equal(app.normalizeSupport({ pedestalHeight: 9999 }).pedestalHeight, 240);
assert.equal(app.normalizeSupport({ pedestalHeight: -1 }).pedestalHeight, 48);
const ped = app.createHead('Pedestrian');
Object.assign(ped, { poleMounted: true, poleMounting: 'side', poleMountSide: 'left', pedestalPosition: 90 });
app.setHeadLayout(ped, 'pedestrian');
const sign = app.createStreetSign('Regulatory');
Object.assign(sign, { regulatoryCode: 'R10-11', armPosition: 144, spanPosition: 200, poleHeight: 150, pedestalPosition: 55 });
assert.ok(app.isRegulatorySign(sign));
const project = { version: 1, support, heads: [head, ped], selectedId: head.id, streetSigns: [sign], spacing: 12, alignment: 'center' };
app.ensureArmPositions(project);
app.ensureStreetSignPositions(project);
assert.equal(app.hasSupport(project), true);
assert.equal(app.canSpaceHeadsEvenly(project), false);
assert.equal(head.pedestalPosition, support.pedestalHeight + 6 + geometry.height / 2);
const layout = app.scene(project);
const first = layout.heads[0], second = layout.heads[1];
assert.equal(first.y + first.geometry.height + 6, layout.supportOffset.y);
assert.ok(second.x + second.geometry.width / 2 < first.x + first.geometry.width / 2);
assert.equal(layout.streetSigns[0].mounting, 'pedestal');
assert.equal(layout.streetSigns[0].y + layout.streetSigns[0].geometry.height / 2, support.pedestalHeight - 55 + layout.supportOffset.y);
const svg = app.renderSVG(project);
assert.ok(svg.includes('pedestalPole'));
assert.ok(svg.includes('pedestalTopFitter'));
assert.ok(svg.includes('pedestal-bands'));
assert.ok(!/NaN|undefined|Infinity/.test(svg));
assert.ok(app.renderPreview(project).includes('data-drag-axis="vertical"'));
assert.ok(app.renderPreview(project).includes('class="mastScene"'));
app.setArmPosition(ped, support, 10000);
assert.equal(ped.pedestalPosition, support.pedestalHeight - app.headGeometry(ped).height / 2);
app.setStreetSignPosition(sign, support, -100);
assert.equal(sign.pedestalPosition, 16 + app.streetSignGeometry(sign).height / 2);
const restored = app.restoreProject(JSON.stringify(project));
assert.equal(restored.support.type, 'pedestal');
assert.equal(restored.support.pedestalHeight, 120);
assert.equal(restored.heads[0].dad, true);
assert.equal(restored.heads[0].orientation, 'vertical');
assert.equal(restored.heads[0].indications[1].size, 8);
assert.equal(restored.heads[1].pedestrian, true);
assert.equal(restored.heads[1].pedestalPosition, ped.pedestalPosition);
assert.equal(restored.streetSigns[0].pedestalPosition, sign.pedestalPosition);
assert.equal(restored.streetSigns[0].armPosition, 144);
assert.equal(restored.streetSigns[0].spanPosition, 200);
assert.equal(restored.streetSigns[0].poleHeight, 150);
const priorHeadPosition = ped.pedestalPosition, priorSignPosition = sign.pedestalPosition;
for (const type of ['mast-arm', 'span-wire', 'none', 'pedestal']) {
  project.support.type = type;
  app.ensureArmPositions(project);
  app.ensureStreetSignPositions(project);
  assert.ok(!/NaN|undefined|Infinity/.test(app.renderSVG(project)));
}
assert.equal(ped.pedestalPosition, priorHeadPosition);
assert.equal(sign.pedestalPosition, priorSignPosition);
for (const next of ['hawk', 'cluster', 'cluster-above', 'cluster-below', 'linear']) {
  app.setHeadLayout(head, 'dad'); app.setHeadLayout(head, next);
  assert.equal(head.dad, false);
}
const empty = { ...project, heads: [], streetSigns: [] };
assert.equal(app.hasDrawing(empty), true);
assert.ok(app.renderSVG(empty).includes('pedestalPole'));
assert.ok(!/NaN|undefined|Infinity/.test(app.renderSVG(empty)));
console.log('DAD geometry, fixed indications, lens sizes, pedestal bounds, independent mounting, restoration, support switching and shared preview/export passed');
app.setHeadLayout(head, 'dad');
head.pedestalPosition = app.armPositionBounds(head, support).max;
ped.pedestalPosition = 80;
sign.pedestalPosition = 50;
const oldCenter = head.pedestalPosition;
app.setPedestalHeight(project, 144);
assert.equal(head.pedestalPosition, oldCenter + 24);
assert.equal(ped.pedestalPosition, 80);
assert.equal(sign.pedestalPosition, 50);
app.setPedestalHeight(project, 48);
assert.ok(ped.pedestalPosition <= 48 - app.headGeometry(ped).height / 2);
assert.ok(sign.pedestalPosition <= 48 - app.streetSignGeometry(sign).height / 2);
assert.ok(!/NaN|undefined|Infinity/.test(app.renderSVG(project)));
console.log('Pole-height changes carry top-mounted heads, retain accessory heights and clamp out-of-bounds mounts');

// The ordinary head on a pedestal can become a pedestrian head directly;
// selecting a layout must not require adding a separate supplementary head.
const primary = app.createHead('Pedestal pedestrian');
const pedestal = app.normalizeSupport({ type: 'pedestal' });
app.setHeadLayout(primary, 'pedestrian', pedestal);
assert.equal(primary.pedestrian, true);
assert.equal(primary.poleMounted, true);
const pedestrianProject = { version: 1, support: pedestal, heads: [primary], streetSigns: [], spacing: 12 };
app.ensureArmPositions(pedestrianProject);
assert.equal(app.restoreProject(JSON.stringify(pedestrianProject)).heads[0].pedestrian, true);
assert.ok(!/NaN|undefined/.test(app.renderSVG(pedestrianProject)));
console.log('Primary pedestal heads can select Pedestrian directly and retain it after restoration');
